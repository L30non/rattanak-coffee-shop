"use client";

import { useCallback, useSyncExternalStore } from "react";
import km from "@/messages/km.json";
import { type Locale } from "@/lib/i18n/config";
import {
  getServerSnapshot,
  getSnapshot,
  setLocale,
  subscribe,
} from "@/lib/i18n/store";

/**
 * Translation uses the English source text as the lookup key (the gettext
 * approach) rather than invented ids like "cart.empty.title". Two reasons:
 * the JSX still reads as English so the code stays reviewable, and a missing
 * or not-yet-translated entry falls back to correct English automatically
 * instead of leaking a key name into the UI.
 *
 * Khmer entries are generated by scripts/translate-i18n.mjs and are meant to
 * be hand-editable afterwards — machine translation into Khmer needs cleanup.
 */
const DICTIONARIES: Record<Locale, Record<string, string>> = {
  en: {},
  km: km as Record<string, string>,
};

export type TranslateVars = Record<string, string | number>;

export type TranslateFn = (text: string, vars?: TranslateVars) => string;

function translate(
  locale: Locale,
  text: string,
  vars?: TranslateVars,
): string {
  let out = DICTIONARIES[locale][text] ?? text;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.split(`{${name}}`).join(String(value));
    }
  }
  return out;
}

export function useI18n(): {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: TranslateFn;
} {
  const locale = useSyncExternalStore(
    subscribe,
    getSnapshot,
    getServerSnapshot,
  );

  const t = useCallback<TranslateFn>(
    (text, vars) => translate(locale, text, vars),
    [locale],
  );

  return { locale, setLocale, t };
}

/** Convenience for components that only need the translate function. */
export function useTranslate(): TranslateFn {
  return useI18n().t;
}
